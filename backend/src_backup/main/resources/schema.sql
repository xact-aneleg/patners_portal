CREATE TABLE IF NOT EXISTS pp_reg_locations (
    id                  SERIAL   PRIMARY KEY,
    registration_id     INTEGER  NOT NULL REFERENCES pp_registrations(id) ON DELETE CASCADE,
    loc                 VARCHAR(3),  whs VARCHAR(3),
    loc_name            VARCHAR(60), region VARCHAR(40),
    stock_loc           BOOLEAN  DEFAULT FALSE,
    physical_addr1      VARCHAR(60), physical_addr2 VARCHAR(60),
    physical_addr3      VARCHAR(60), physical_addr4 VARCHAR(60)
);

CREATE TABLE IF NOT EXISTS pp_reg_users (
    id                  SERIAL   PRIMARY KEY,
    registration_id     INTEGER  NOT NULL REFERENCES pp_registrations(id) ON DELETE CASCADE,
    username            VARCHAR(30),  full_name   VARCHAR(80),
    email               VARCHAR(100), default_loc VARCHAR(3),
    access_grp          VARCHAR(10)
);

CREATE TABLE IF NOT EXISTS pp_workflow_events (
    id                  SERIAL   PRIMARY KEY,
    registration_id     INTEGER  NOT NULL REFERENCES pp_registrations(id),
    actor_id            INTEGER  REFERENCES pp_partners(id),
    actor_name          VARCHAR(80),
    event_type          VARCHAR(40) NOT NULL,
    from_status         VARCHAR(40), to_status VARCHAR(40),
    comments            TEXT,
    created_at          TIMESTAMP DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS pp_conversion_jobs (
    id                  SERIAL   PRIMARY KEY,
    registration_id     INTEGER  NOT NULL REFERENCES pp_registrations(id),
    status              VARCHAR(20) DEFAULT 'PENDING',
    started_at          TIMESTAMP, completed_at TIMESTAMP,
    log_output          TEXT,
    created_at          TIMESTAMP DEFAULT NOW()
);

