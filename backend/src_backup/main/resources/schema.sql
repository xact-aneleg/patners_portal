    master_or_slave VARCHAR(10)  DEFAULT 'MASTER',
    postal_addr1    VARCHAR(60),  postal_addr2 VARCHAR(60),
    postal_addr3    VARCHAR(60),  postal_addr4 VARCHAR(60),
    physical_addr1  VARCHAR(60),  physical_addr2 VARCHAR(60),
    physical_addr3  VARCHAR(60),  physical_addr4 VARCHAR(60),
    telephone       VARCHAR(30),  fax          VARCHAR(30),
    company_email   VARCHAR(100), company_domain VARCHAR(100),
    reg_number      VARCHAR(30),  vat_number   VARCHAR(30),
    year_end_month  INTEGER,      vat_rate     NUMERIC(5,2) DEFAULT 15,
    bank_name       VARCHAR(60),  bank_branch  VARCHAR(60),
    bank_branch_code VARCHAR(20), bank_account VARCHAR(30),
    multi_currency  BOOLEAN      DEFAULT FALSE,
    local_currency  VARCHAR(40),  currency_code VARCHAR(6),
    period_gl       INTEGER,      period_cb    INTEGER,
    period_dl       INTEGER,      period_sa    INTEGER,
